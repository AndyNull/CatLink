package router

import (
	"github.com/flipped-aurora/gin-vue-admin/server/api/v1/catlink"
	"github.com/flipped-aurora/gin-vue-admin/server/middleware"
	"github.com/gin-gonic/gin"
)

var CatLinkApi = catlink.CatApiGroup

type CatLinkRouter struct{}

// InitCatLinkRouter 挂载 CatLink /api/v1 业务路由（App 契约前缀 /api）
func (r *CatLinkRouter) InitCatLinkRouter(Public, CatAdmin *gin.RouterGroup) {
	catlink.AutoMigrateCatTables()
	catlink.BootstrapCatLinkAccess()
	v1 := Public.Group("v1")
	{
		v1.GET("/health", CatLinkApi.Health)
		v1.GET("/auth/policy", CatLinkApi.AuthPolicy)
		v1.POST("/auth/captcha", middleware.CatLinkAuthLimit(), CatLinkApi.Captcha)
		v1.POST("/auth/login", middleware.CatLinkAuthLimit(), CatLinkApi.Login)
		v1.POST("/auth/register", middleware.CatLinkAuthLimit(), CatLinkApi.Register)
		v1.POST("/auth/refresh", middleware.CatLinkAuthLimit(), CatLinkApi.Refresh)
		v1.POST("/auth/email/verify", middleware.CatLinkAuthLimit(), CatLinkApi.VerifyEmail)
		v1.POST("/auth/email/resend", middleware.CatLinkAuthLimit(), CatLinkApi.ResendEmail)
		v1.POST("/auth/password/reset", middleware.CatLinkAuthLimit(), CatLinkApi.RequestPasswordReset)
		v1.POST("/auth/password/reset/confirm", middleware.CatLinkAuthLimit(), CatLinkApi.ConfirmPasswordReset)
		v1.GET("/encouragements/random", CatLinkApi.Random)
		v1.GET("/public/cats", CatLinkApi.List)
		v1.GET("/public/cats/:id", CatLinkApi.Detail)
		v1.GET("/public/cats/:id/timeline", CatLinkApi.Timeline)
		v1.GET("/community/feed", CatLinkApi.Feed)
		v1.GET("/location/reverse", middleware.CatLinkLocationLimit(), CatLinkApi.ReverseLocation)
		v1.GET("/location/ip", middleware.CatLinkLocationLimit(), CatLinkApi.IPLocation)
		v1.GET("/community/posts/:postId", CatLinkApi.DetailPost)
		v1.GET("/community/posts/:postId/comments", CatLinkApi.Comments)
		v1.GET("/users/:accountId/public", CatLinkApi.UserPublic)
		v1.GET("/share/cats/:code", CatLinkApi.SharedCat)
		v1.GET("/ad/config", CatLinkApi.Config)
		v1.GET("/version/check", CatLinkApi.Check)
		v1.GET("/missing-cases", CatLinkApi.ListMissingCases)
	}
	v1logout := Public.Group("v1")
	v1logout.POST("/auth/logout", catlink.LogoutBearer(), CatLinkApi.Logout)

	v1s := Public.Group("v1")
	v1s.Use(catlink.AuthBearer())
	v1s.Use(middleware.BusinessOperationRecord())
	{
		v1s.GET("/auth/getUserInfo", CatLinkApi.GetUserInfo)
		v1s.GET("/account", CatLinkApi.Account)
		v1s.GET("/account/export", CatLinkApi.ExportAccount)
		v1s.PATCH("/account", CatLinkApi.UpdateAccount)
		v1s.GET("/account/devices", CatLinkApi.Devices)
		v1s.DELETE("/account/devices/:deviceId", CatLinkApi.RevokeDevice)
		v1s.GET("/account/notifications", CatLinkApi.Notifications)
		v1s.GET("/account/notifications/stream", CatLinkApi.NotificationStream)
		v1s.POST("/account/notifications/read", CatLinkApi.MarkNotifRead)
		v1s.GET("/account/safety", CatLinkApi.SafetyList)
		v1s.POST("/account/push-devices", CatLinkApi.RegisterPushDevice)
		v1s.DELETE("/account/push-devices/:token", CatLinkApi.DisablePushDevice)
		v1s.POST("/account/identity", CatLinkApi.RequestIdentityBadge)
		v1s.GET("/auth/notifications", CatLinkApi.Notifications)
		v1s.PUT("/auth/notifications/read", CatLinkApi.MarkNotifRead)
		v1s.GET("/community/feed/following", CatLinkApi.FollowingFeed)
		v1s.POST("/community/posts", CatLinkApi.CreatePost)
		v1s.POST("/community/posts/:postId/like", CatLinkApi.LikePost)
		v1s.POST("/community/posts/:postId/bookmarks", CatLinkApi.ToggleBookmark)
		v1s.POST("/community/posts/:postId/comments", CatLinkApi.AddComment)
		v1s.POST("/community/comments/:commentId/like", CatLinkApi.LikeComment)
		v1s.POST("/community/users/:accountId/follow", CatLinkApi.FollowUser)
		v1s.POST("/community/users/:accountId/:kind", CatLinkApi.ToggleSafety)
		v1s.POST("/public/cats/:id/timeline", CatLinkApi.AddTimeline)
		v1s.POST("/community/reports", CatLinkApi.SubmitCommunityReport)
		v1s.POST("/moderation-actions/:actionId/appeals", CatLinkApi.SubmitModerationAppeal)
		v1s.POST("/community/adoption-applications", CatLinkApi.ApplyAdoption)
		v1s.GET("/adoption-applications", CatLinkApi.AdoptionApplications)
		v1s.GET("/adoption-applications/:applicationId/timeline", CatLinkApi.AdoptionTimeline)
		v1s.POST("/adoption-applications/:applicationId/timeline", CatLinkApi.AddAdoptionEvent)
		v1s.POST("/missing-cases", CatLinkApi.CreateMissingCase)
		v1s.POST("/missing-cases/:caseId/sightings", CatLinkApi.AddMissingSighting)
		v1s.PUT("/missing-cases/:caseId/close", CatLinkApi.CloseMissingCase)
		v1s.POST("/rescue-tasks", CatLinkApi.CreateRescueTask)
		v1s.GET("/rescue-tasks", CatLinkApi.ListRescueTasks)
		v1s.PUT("/rescue-tasks/:taskId", CatLinkApi.UpdateRescueTask)
		v1s.POST("/public/cats", CatLinkApi.Publish)
		v1s.POST("/public/cats/:id", CatLinkApi.UpdatePublic)
		v1s.DELETE("/public/cats/:id", CatLinkApi.ArchivePublic)
		v1s.POST("/public/cats/:id/follow", CatLinkApi.Follow)
		v1s.DELETE("/public/cats/:id/follow", CatLinkApi.Unfollow)
		v1s.GET("/public/me/followed-cats", CatLinkApi.Followed)
		v1s.POST("/media/upload", CatLinkApi.UploadMedia)
		v1s.GET("/media/:id", CatLinkApi.DownloadPrivateMedia)
		v1s.DELETE("/media/:id", CatLinkApi.DeleteTemporaryMedia)
		v1s.POST("/share/media", CatLinkApi.UploadMedia)
		v1s.POST("/share/cats", CatLinkApi.CreateCatShare)
		v1s.POST("/conversations/start", CatLinkApi.StartConversation)
		v1s.GET("/conversations", CatLinkApi.ConversationList)
		v1s.GET("/conversations/:conversationId/messages", CatLinkApi.ConversationMessages)
		v1s.POST("/conversations/:conversationId/messages", CatLinkApi.SendMessage)
		v1s.POST("/reports", CatLinkApi.Submit)
		v1s.POST("/share/preview", CatLinkApi.CreateShare)
		v1s.POST("/vault/sync", CatLinkApi.VaultSync)
		v1s.POST("/vault/enable", CatLinkApi.VaultEnable)
	}

	// GVA 管理端：原生 x-token JWT + 超级管理员权限。
	admin := CatAdmin.Group("v1/moderation")
	admin.Use(catlink.CatAdminOnly())
	admin.Use(middleware.OperationRecord())
	{
		admin.GET("/stats", CatLinkApi.Stats)
		admin.GET("/posts", CatLinkApi.Posts)
		admin.PUT("/posts/:id/lock", CatLinkApi.LockPost)
		admin.DELETE("/posts/:id", CatLinkApi.DeletePost)
		admin.GET("/cats", CatLinkApi.Cats)
		admin.PUT("/cats/:id/state", CatLinkApi.SetCatState)
		admin.PUT("/cats/:id/status", CatLinkApi.SetCatStatus)
		admin.GET("/reports", CatLinkApi.Reports)
		admin.PUT("/reports/:id/resolve", CatLinkApi.ResolveReport)
		admin.GET("/moderation-appeals", CatLinkApi.ModerationAppeals)
		admin.PUT("/moderation-appeals/:id", CatLinkApi.ResolveModerationAppeal)
		admin.GET("/quotes", CatLinkApi.Quotes)
		admin.POST("/quotes", CatLinkApi.SaveQuote)
		admin.POST("/quotes/import", CatLinkApi.ImportQuotes)
		admin.PUT("/quotes/:id", CatLinkApi.UpdateQuote)
		admin.DELETE("/quotes/:id", CatLinkApi.DeleteQuote)
		admin.GET("/encouragement-ai/config", CatLinkApi.EncouragementAIConfig)
		admin.PUT("/encouragement-ai/config", CatLinkApi.SaveEncouragementAIConfig)
		admin.POST("/encouragement-ai/test", CatLinkApi.TestEncouragementAI)
		admin.GET("/email/config", CatLinkApi.EmailConfig)
		admin.PUT("/email/config", CatLinkApi.SaveEmailConfig)
		admin.POST("/email/test", CatLinkApi.TestEmailConfig)
		admin.GET("/ads", CatLinkApi.Ads)
		admin.POST("/ads", CatLinkApi.SaveAd)
		admin.PUT("/ads/:id", CatLinkApi.UpdateAd)
		admin.DELETE("/ads/:id", CatLinkApi.DeleteAd)
		admin.GET("/versions", CatLinkApi.Versions)
		admin.POST("/versions", CatLinkApi.SaveVersion)
		admin.DELETE("/versions/:id", CatLinkApi.DeleteVersion)
		admin.GET("/adoptions", CatLinkApi.Adoptions)
		admin.PUT("/adoptions/:id/status", CatLinkApi.SetAdoptionStatus)
		admin.POST("/notifications/broadcast", CatLinkApi.Broadcast)
		admin.GET("/notifications/campaigns", CatLinkApi.AnnouncementCampaigns)
		admin.PUT("/notifications/campaigns/:id/withdraw", CatLinkApi.WithdrawAnnouncement)
		admin.GET("/metrics", CatLinkApi.Metrics)
		admin.GET("/metrics/prometheus", CatLinkApi.MetricsPrometheus)
		admin.GET("/retention", CatLinkApi.RetentionPolicies)
		admin.GET("/retention/preview", CatLinkApi.RetentionPreview)
		admin.POST("/retention", CatLinkApi.SaveRetentionPolicy)
		admin.GET("/identity-badges", CatLinkApi.IdentityBadges)
		admin.PUT("/identity-badges/:id", CatLinkApi.ResolveIdentityBadge)
	}
}
